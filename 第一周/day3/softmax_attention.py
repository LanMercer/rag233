# -*- coding: utf-8 -*-
"""
Day 3 配套脚本：极简 softmax 手算 —— 3 个词的自注意力权重矩阵
================================================================
运行方法（在 llm 环境中）：
    conda activate llm
    cd "D:\Lan\研究生\技术学习\大模型算法\第一周\day3"
    python softmax_attention.py

本脚本只用 numpy，手动完成"自注意力"的 3 步：
    1. 每个词生成 Q、K、V
    2. Q 与所有 K 做点积 → 分数 → softmax → 权重（每行和为 1）
    3. 权重 × V 加权平均 → 融合上下文的新表示

数学视角：3x3 权重矩阵每行和为 1、每格 0~1 —— 长得和"转移概率矩阵"一模一样。

★ 本版是"逐行教学版"：代码里每一行都加了详细注释，
  把 Python 语法（列表、for、函数、f-string、矩阵乘法等）逐个讲清楚。
★ 建议配合教程第 5 步逐段读；读完动手把第 6 段的 X2 再改着玩。
"""

# =====================================================================
# 【课前语法速查】本脚本用到的 Python 语法，遇到不懂的回来查
# =====================================================================
#  import numpy as np      → 导入一个叫 numpy 的库，并给它起个短名 np
#                            （numpy 是做矩阵/数值计算的库，装 torch 时已自动带上）
#
#  words = ["猫", "追", "狗"]   → 列表（list）：一串东西，用方括号 [] 包起来
#                                 里面的每个东西叫"元素"，用 下标（从0开始） 访问：
#                                 words[0] = "猫"，words[1] = "追"，words[2] = "狗"
#
#  np.eye(3)                → 调用 numpy 里的 eye 函数：生成一个 3×3 单位矩阵
#                             单位矩阵 = 对角线全是 1、其他全是 0 的方阵
#
#  Wq = Wk = Wv = np.eye(3) → 链式赋值：一条语句给 3 个变量赋同一个值，
#                             Wq、Wk、Wv 都指向同一个 3×3 单位矩阵
#
#  X @ Wq                   → @ 是"矩阵乘法"符号（Python 3.5 以后才有），
#                             普通乘法 * 是"对应位置相乘"，@ 是"行乘列求和"，完全不同！
#
#  K.T                      → .T 表示"转置"：把矩阵的行和列互换。
#                             单位矩阵转置还是自己（对称），这里主要是为了演示写法
#
#  for i, w in enumerate(words):  → 遍历列表，同时拿到"位置编号 i"和"元素 w"
#                              enumerate = "数数器"，它会吐出 (0, "猫") (1, "追") (2, "狗")
#
#  f"{w}: Q={Q[i]}"         → f-string 格式化字符串：花括号 {} 里放变量/表达式，
#                             运行时会自动把值填进去。f 必须写在引号前面
#
#  def softmax(row): ...    → 定义函数：把一段代码打包，起个名字，以后反复调用
#                             row 是"参数"（喂给函数的东西），return 是"结果"（吐出来的东西）
#
#  [softmax(r) for r in scores]  → 列表推导式：一行代码生成新列表
#                             读法："对 scores 里的每一个 r，都算一遍 softmax(r)，收进新列表"
#
#  np.round(weights, 4)     → 把数组里的数保留 4 位小数，方便看（不影响原数据）
# =====================================================================

import numpy as np  # 导入 numpy 库，起短名 np（整个脚本都要用它）

# ---------------------------------------------------------------------
# 第 1 段：3 个词的"词向量"（极简：one-hot，便于手算）
# ---------------------------------------------------------------------
# 什么是 one-hot（独热编码）？
#   每个词用一个只有"一个位置是 1、其他全是 0"的向量表示：
#   猫 = [1,0,0]  追 = [0,1,0]  狗 = [0,0,1]
#   第 1 个位置代表"猫"，第 2 个位置代表"追"，第 3 个位置代表"狗"。
#   真实模型不用 one-hot，用"学出来的稠密向量"（后面第 6 段会让你体会区别）。

words = ["猫", "追", "狗"]  # 列表：存放 3 个词的显示名字（打印时用）

# np.eye(3) 生成 3×3 单位矩阵：
#   [ [1, 0, 0],
#     [0, 1, 0],
#     [0, 0, 1] ]
# 正好每一行就是一个词的 one-hot 向量，所以 X 直接当"词向量矩阵"用。
X = np.eye(3)  # X 的形状是 (3, 3) = "3 个词 × 3 维向量"，第 i 行是第 i 个词的向量

# ---------------------------------------------------------------------
# 第 2 段：生成 Q / K / V（每个词三个角色）
# ---------------------------------------------------------------------
# 真实模型里，词向量要乘上"训练学出来的矩阵 Wq/Wk/Wv"才得到 Q/K/V。
# 这里先把 Wq/Wk/Wv 都设成单位矩阵，这样 Q=K=V=词向量本身，
# 排除一切干扰，让你只盯着"计算流程"看。
Wq = Wk = Wv = np.eye(3)  # 链式赋值：一行给三个变量赋同一个值

Q = X @ Wq  # @ = 矩阵乘法。X(3×3) 乘 Wq(3×3) → Q(3×3)。Q 的第 i 行 = 词 i 的 Query
K = X @ Wk  # K 的第 i 行 = 词 i 的 Key
V = X @ Wv  # V 的第 i 行 = 词 i 的 Value

print("===== 1. 每个词都有 Q / K / V（这里 Q=K=V=词向量）=====")
# for 循环遍历 words 列表；enumerate 同时提供"编号 i"和"元素 w"
for i, w in enumerate(words):  # 第 1 圈：i=0, w="猫"；第 2 圈：i=1, w="追"；第 3 圈：i=2, w="狗"
    # f-string：f 开头，{} 里的内容会被替换成实际值，\n 是换行
    print(f"{w}: Q={Q[i]}  K={K[i]}  V={V[i]}")

# ---------------------------------------------------------------------
# 第 1 步：Q 与所有 K 做点积 → 相似度分数
# ---------------------------------------------------------------------
# scores[i][j] = 词 i 对 词 j 的"相似度分数"。
# 用矩阵乘法一步算完：Q 的每一行 乘 K 转置的每一列。
scores = Q @ K.T  # Q(3×3) @ K^T(3×3) → scores(3×3)
print("\n===== 2. 相似度分数矩阵 scores = Q·K^T =====\n", np.round(scores, 4))
# np.round(x, 4)：保留 4 位小数，纯显示用

# ---------------------------------------------------------------------
# 第 2 步：softmax —— 把每一行分数变成"概率分布"
# ---------------------------------------------------------------------
def softmax(row):
    # 函数 4 要素：关键字 def + 函数名 + (参数) + 冒号，函数体必须缩进 4 个空格
    # 这里 row 是"一行分数"，比如 [1, 0, 0]

    row = row - row.max()
    # 先减去这一行的最大值（数学上不影响结果，但能防止指数爆炸溢出）
    # row.max() = 取这一行的最大值；row - 最大值 = 每个数都减掉它

    e = np.exp(row)
    # np.exp(x) = e 的 x 次方（e≈2.718）。softmax 的核心就是"取指数"
    # 取指数后，原来的分数差距会被"放大"，大分数更突出（这就是 softmax 的作用）

    return e / e.sum()
    # return = 把结果还给调用方。e.sum() = 这一行所有数求和
    # 每个数 ÷ 总和 → 所有数都变成 0~1 之间，且加起来 = 1 = 一个概率分布！
    # 这就是面试常说的"softmax 输出 = 概率分布"

weights = np.array([softmax(r) for r in scores])
# 列表推导式（语法速查里有）：对 scores 的三行，每行都做一遍 softmax
# np.array(...) 把结果列表包成 numpy 数组，方便后面做矩阵乘法
# 结果 weights(3×3)：每行和为 1

print("\n===== 3. softmax 之后的权重矩阵（每行和为 1）=====")
print(np.round(weights, 4))
print("每行之和:", np.round(weights.sum(axis=1), 4))  # 应全为 1.0
# weights.sum(axis=1) = 按"行"求和（axis=0 是按列），验证每行确实是概率分布

# ---------------------------------------------------------------------
# 第 3 步：权重 × V 加权平均 → 融合上下文后的新表示
# ---------------------------------------------------------------------
out = weights @ V  # 矩阵乘法：weights(3×3) @ V(3×3) → out(3×3)
# out 的第 i 行 = 把 V 的三行按 weights 第 i 行的权重加权平均
# 这正是 Day 2 那句话："注意力 = 对 Value 的加权平均"
print("\n===== 4. 输出 = 权重 @ V（融合上下文后的新词向量）=====")
for i, w in enumerate(words):  # 又是 for + enumerate：遍历打印每个词
    print(f"{w} 的新表示: {np.round(out[i], 4)}")

# ---------------------------------------------------------------------
# 数学视角解读
# ---------------------------------------------------------------------
print("\n===== 5. 数学视角 =====")
print("权重矩阵每一行 = 一个概率分布（非负、和为 1），")
print("整张矩阵 = 3 词之间的'转移概率矩阵'（和马尔可夫链的转移矩阵长得一样）。")
print("'追'(第 2 行)对'猫'和'狗'的权重相同，是因为 one-hot 词向量看不出词义关系——")
print("真实模型用学习出来的词向量后，'追'会更关注'猫''狗'这类有语义关联的词。")

# ---------------------------------------------------------------------
# 第 6 段（升级实验）：给"猫""狗"加上共同的"动物"维度
# ---------------------------------------------------------------------
# 上一段用的是 one-hot 词向量，词和词之间看不出任何关系。
# 这一段我们"手动造假"一个能体现语义的词向量：
#   猫 = [1,0,1]  → 第 1 维是"猫"自己，第 3 维是"动物"（猫和狗都有 1）
#   追 = [0,1,0]  → 第 2 维是"追"，没有"动物"维度
#   狗 = [1,0,1]  → 和猫共享"动物"维度
# 观察：共享语义维度的词，注意力会不会自动"互相吸引"？

print("\n===== 6. 升级版：'猫''狗'共享'动物'维度的词向量 =====")
X2 = np.array([
    [1, 0, 1],  # 第 1 行 = 猫的词向量（有"动物"维度）
    [0, 1, 0],  # 第 2 行 = 追的词向量（没有"动物"维度）
    [1, 0, 1],  # 第 3 行 = 狗的词向量（有"动物"维度）
]).astype(float)
# 注意：np.array 默认自动识别元素类型。这里 1 是整数，后面矩阵乘法需要小数，
# 所以用 .astype(float) 把整个数组转成"浮点数"（带小数点的数）
# （其实这里整数也能乘，写成 float 是为了符合真实场景 + 展示这个常用方法）

# 下面 3 行和前面第 2 段完全一样的套路：生成 Q2/K2/V2 → 算分数 → softmax
# 唯一区别：X 换成了 X2（带语义的词向量）
Q2 = X2 @ np.eye(3)      # Query：因为 W 还是单位矩阵，Q2 = X2 本身
K2 = X2 @ np.eye(3)      # Key
V2 = X2 @ np.eye(3)      # Value
scores2 = Q2 @ K2.T      # 相似度分数（和前面 scores 同一个公式）
weights2 = np.array([softmax(r) for r in scores2])  # softmax 变概率分布

print("升级后的权重矩阵（每行和为 1）:")
print(np.round(weights2, 4))
print("注意第 1、3 行（'猫''狗'）：它们对彼此的权重明显变大了！")
print("（one-hot 时 0.212 → 共享'动物'维度后 0.468；对'追'则掉到 0.063）")
print("结论：词向量承载语义 → 注意力自动聚焦到同类词。")
